function eventFor(key, profile, index) {
  const moment = MOMENTS[index];
  const label = profile.labels[index % profile.labels.length];
  return {
    id: `${key}_longtail_${String(index + 1).padStart(2, '0')}`,
    minTier: index < 10 ? 1 : index < 19 ? 2 : 3,
    text: `${moment.where}，你在${profile.place}遇见${profile.name}。${moment.scene}。${moment.action}。${profile.object}把这个人从“路过的同学”里分出来；${profile.trait}。`,
    choices: [
      {
        label,
        delta: index >= 19 ? 3 : 2,
        response: `${profile.name}没有把你的话当成普通寒暄。${profile.soft}。这一次回应没有变成戏剧性的大事，却像在你们之间多放了一盏小灯，下次再遇见时不必从全然陌生处说起。`,
      },
      {
        label: index % 2 ? '换个轻一点的话题' : '安静陪一会儿',
        delta: 1,
        response: `${moment.quiet}。你没有急着追到最深处，只顺着${profile.object}旁边那点气氛停了一会儿。${profile.name}的反应很轻，却不是敷衍。`,
      },
    ],
  };
}

export const STUDENT_LONGTAIL_PACK_ENRICHMENTS = Object.fromEntries(
  Object.entries(PROFILES).map(([key, profile]) => [
    key,
    { activeChatEvents: MOMENTS.map((_, index) => eventFor(key, profile, index)) },
  ])
);
