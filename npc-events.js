    const topic = base.topic ? `“${base.topic}”` : "那件事";
    const who = base.characterName ? `${base.characterName}` : "当事人";
    if (base.delta > 0) return `长桌旁有人还记得你插手了${topic}。据说${who}私下对你多了几分好感。`;
