const pick = (items, item) => items[(item.lesson - 1) % items.length];

export const lessonMap = Object.fromEntries(
  APPARITION_LESSON_PLAN.map(item => {
    const scene = item.lesson <= 14 || item.lesson >= 25 ? pick(HALL_SCENES, item) : pick(FIELD_SCENES, item);
    const yearText = `五年级第 ${item.lesson} 节`;

    return [item.lesson, {
      atmosphere: scene,
      opening: `威斯考特教授把怀表合上：“${item.title}。幻影移形不是消失的技巧，是把完整的自己带到正确地点的判断。”`,
      keyPoints: item.focus.map((point, index) => ({
        point,
        context: index === 0
          ? `${yearText}先确认${point}。教授要求你能说清楚它，而不是只觉得自己明白。`
          : index === 1
            ? `训练进入第二步：${point}。如果这一点开始动摇，就必须停下重建。`
            : `最后检查${point}。移动完成以后，安全闭环才算结束。`
      }))
    }];
  })
);
