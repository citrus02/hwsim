function buildAtmosphere(item) {
  const scene = item.year === 1 ? pick(FIRST_YEAR_SCENES, item) : pick(SECOND_YEAR_SCENES, item);
  const yearText = item.year === 1 ? `一年级第 ${item.lesson} 节` : `二年级第 ${item.lesson - 34} 节`;
  return `${scene}这是${yearText}飞行课，主题是「${item.title}」。今天的训练目标不是把路线飞得漂亮，而是完成这项任务：${item.drill}`;
}

function buildOpening(item) {
  const reminder = item.year === 1
    ? "你们现在学的每个小动作，以后都会在高空、雨里、比赛里救你一次。"
    : "二年级开始，速度、队友和球路都会同时出现；你不能只会飞，还要会判断。";
  return `「${item.title}。」霍琦教授吹了一声短哨，等队伍安静下来才继续，「${item.drill}」她把训练路线指给你们看，「${reminder}${item.risk}所以今天谁想靠胆子蒙过去，我会让他立刻降落。」`;
}

function buildKeyPoint(item, point, index) {
  const labels = ["观察与判断", "动作与控制", "恢复与复盘"];
  const suffix = [
    "先确认环境、风向、同伴位置和目标点，再让扫帚行动",
    "用身体重心和手腕细节完成动作，不把扫帚当成需要制服的东西",
    "动作结束后回到安全高度、路线和队列，再判断下一步"
  ][index];

  const contexts = [
    `霍琦教授让你们先站在地面看完整条路线，要求每个人说出最容易出问题的位置。「看见危险不是胆小，」她说，「是你还来得及选择。」她特别点出这节课的风险：${item.risk}`,
    `她骑上扫帚示范了一遍，动作很小，几乎没有多余摆动。轮到学生练习时，她会立刻指出手腕、膝盖、视线或肩膀的偏差：「飞行不是大动作赢，小动作才说明你真的知道扫帚在做什么。」`,
    `练习结束前，霍琦教授要求所有人按顺序回到队列，报告自己在哪一步失控、怎么修正、下次要提前做什么。「如果你只记得自己飞完了，」她合上评分表，「那你其实什么也没学会。」`
  ];

  return {
    point: `${point}：${labels[index]}——${suffix}`,
    context: contexts[index]
  };
}

export const lessonMap = Object.fromEntries(
  FLIGHT_LESSON_PLAN.map(item => [
    item.lesson,
    {
      atmosphere: buildAtmosphere(item),
      opening: buildOpening(item),
      keyPoints: item.focus.map((point, index) => buildKeyPoint(item, point, index))
    }
  ])
);

