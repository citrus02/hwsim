export function getGiftTier(characterKey, itemName) {
  const prefs = GIFT_PREFERENCES[characterKey];
  if (!prefs) return "neutral";
  for (const tier of ["love", "like", "neutral", "dislike", "hate"]) {
    if (prefs[tier]?.includes(itemName)) return tier;
  }
  return "neutral";
}

export function getGiftResponse(characterKey, tier) {
  const pool = GIFT_RESPONSES[tier] || GIFT_RESPONSES.neutral;
  return pool[Math.floor(Math.random() * pool.length)];
}

export function getGiftDelta(tier) {
  return GIFT_TIERS[tier]?.delta ?? 1;
}

export function getCharacterGiftPrefs(characterKey) {
  return GIFT_PREFERENCES[characterKey] || null;
}
